"""The writer: prose that is only allowed to point at evidence ids.

The model never sees a URL and never sees page text. It sees a numbered list of
claims, each with an id. Everything it emits must reference those ids, and the
references section is generated by *us* from the store.

That inversion is the whole trick. If the writer could type a URL, it could
invent one, and no amount of prompting would make that checkable. If it can only
type an id, then every citation resolves to a record whose quote was already
verified against a cached page. The citation graph becomes closed.

Three checks run on every draft:

  unknown_citation   an id that is not in the citable set
  uncited_paragraph  a factual paragraph with no id at all
  raw_url            a URL in the prose (references are generated, not written)

Failing drafts get one repair turn with the exact problem list. If they still
fail, the report is marked not-ok and the CLI refuses to publish it. Fail closed:
a report with a dangling citation is worse than no report.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Sequence
from urllib.parse import urlsplit

from .evidence import Evidence, EvidenceStore
from .llm import LLMClient, LLMResponse, Message, Usage
from .planning import Plan
from .structured import strip_fences

BRACKET_RE = re.compile(r"\[([^\[\]]*)\]")
ID_RE = re.compile(r"ev_[0-9a-f]{8}")
URL_RE = re.compile(r"https?://\S+")

# Models occasionally typeset citations with full-width or CJK brackets, e.g.
# 【ev_1a2b3c4d】. Those are visually identical to [ev_1a2b3c4d] and pass a human
# read, but BRACKET_RE only knows ASCII, so the id was never extracted and the
# report shipped with zero machine-readable citations while every check passed.
# Normalising at the boundary costs nothing and closes that hole.
_UNICODE_BRACKETS = str.maketrans(
    {
        "\u3010": "[",  # 【
        "\u3011": "]",  # 】
        "\uff3b": "[",  # ［
        "\uff3d": "]",  # ］
        "\ufe5d": "[",  # ﹝
        "\ufe5e": "]",  # ﹞
        "\u3014": "[",  # 〔
        "\u3015": "]",  # 〕
        "\u2772": "[",  # ❲
        "\u2773": "]",  # ❳
    }
)


def normalize_citations(text: str) -> str:
    """Map look-alike brackets to ASCII so ids are actually extractable."""
    return (text or "").translate(_UNICODE_BRACKETS)

WRITER_PROMPT = """You write short, dense research briefs for software engineers.

You do NOT have the internet. You have a list of verified evidence records, each
with an id, a claim, a quote and a source domain.

Hard rules:
1. After every factual sentence, cite the ids that support it: [ev_1a2b3c4d].
   Multiple ids go in separate brackets: [ev_aaaabbbb][ev_ccccdddd].
   Lists and tables count: every bullet and every table row needs at least one
   id. If a row is pure synthesis, cite the ids it summarizes; if none support
   it, move the point to Limitations instead.
2. Use ONLY ids from the EVIDENCE list. Never invent an id.
3. NEVER write a URL. A references section is generated from your ids.
4. Do not state anything the evidence does not say. If the evidence is thin,
   one-sided or contradictory, say so under Limitations.
5. No filler. No "in today's fast-paced world", no "in conclusion".
6. Each record may be tagged [support, trust]. If support is "partial", hedge
   the sentence ("at least one source reports..."). If trust is "aggregator",
   prefer a "primary" source making the same point. Never cite a claim more
   strongly than its quote allows.
7. The user message may list UNCOVERED SUB-QUESTIONS. Do not answer those from
   general knowledge. Mention the gap under Limitations and omit that section.

Length: 350-550 words. Output markdown in exactly this shape:

# <specific title, not "Research Report">

## Summary
<3-4 sentences, every one cited>

## <section answering part of the question>
<...>

## <2-4 sections in total>

## Limitations
- <what the evidence cannot establish>
"""

EMPTY_RETRY_PROMPT = """Your previous completion was empty or cut off before any
usable markdown appeared. Return the complete report from the beginning. Include
the level-1 title, a `## Summary`, at least two content sections, and
`## Limitations`. Cite only the evidence ids listed above."""


REPAIR_PROMPT = """Your draft failed citation checks:

{problems}

Return the corrected draft as markdown only, no fences. Change only what is
needed: add ids to every uncited paragraph, bullet, and table row; if no evidence
supports a point, delete it or move it to Limitations. Remove ids that are not
in the evidence list, and delete any URL from the prose. Keep the structure."""


class WriterError(RuntimeError):
    pass


@dataclass(slots=True)
class Problem:
    code: str
    detail: str
    severity: str = "error"


@dataclass(slots=True)
class Report:
    markdown: str
    body: str
    errors: list[Problem] = field(default_factory=list)
    initial_errors: list[Problem] = field(default_factory=list)
    warnings: list[Problem] = field(default_factory=list)
    cited_ids: list[str] = field(default_factory=list)
    unused_ids: list[str] = field(default_factory=list)
    usage: Usage = field(default_factory=Usage)
    repaired: bool = False
    sections: int = 0
    word_count: int = 0

    @property
    def ok(self) -> bool:
        return not self.errors


def domain(url: str) -> str:
    return urlsplit(url).netloc.lower().removeprefix("www.")


def build_brief(items: Sequence[Evidence], *, max_chars: int = 9000) -> str:
    """Compact, id-first view of the evidence. No URLs, no page text."""
    blocks: list[str] = []
    used = 0
    for item in items:
        quote = " ".join(item.quote.split())[:220]
        tag = (
            f" [{item.support}, {item.trust}]"
            if item.support != "unchecked"
            else ""
        )
        block = (
            f"[{item.id}]{tag} {item.claim}\n"
            f'    quote: "{quote}"\n'
            f"    source: {domain(item.url)}"
        )
        if used + len(block) > max_chars:
            break
        blocks.append(block)
        used += len(block)
    return "\n\n".join(blocks)


def extract_ids(text: str) -> list[str]:
    found: list[str] = []
    for match in BRACKET_RE.finditer(normalize_citations(text)):
        for evidence_id in ID_RE.findall(match.group(1)):
            if evidence_id not in found:
                found.append(evidence_id)
    return found


def _iter_blocks(body: str) -> list[tuple[str, str]]:
    """(section, text) for every prose block, split on blank lines.

    Fenced code blocks are skipped: a code sample is not a factual claim and
    demanding a citation for it just forces a useless repair turn.
    """
    blocks: list[tuple[str, str]] = []
    section = ""
    buffer: list[str] = []
    in_fence = False

    def flush() -> None:
        if buffer:
            blocks.append((section, " ".join(buffer)))
            buffer.clear()

    for line in body.splitlines():
        stripped = line.strip()
        if stripped.startswith("```"):
            flush()
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        if stripped.startswith("## "):
            flush()
            section = stripped[3:].strip()
        elif stripped.startswith("# "):
            flush()
            section = ""
        elif not stripped:
            flush()
        else:
            buffer.append(stripped)
    flush()
    return blocks


def check_draft(body: str, allowed: set[str]) -> list[Problem]:
    """Mechanical checks. No model involved — this must be deterministic."""
    problems: list[Problem] = []
    body = normalize_citations(body)

    for evidence_id in extract_ids(body):
        if evidence_id not in allowed:
            problems.append(
                Problem(
                    "unknown_citation",
                    f"{evidence_id} is not in the citable evidence set",
                )
            )

    if not extract_ids(body):
        # A report with no ids is not a cited report. Without this check an
        # uncitable format (e.g. 【...】) produced a green draft that cited
        # nothing at all — the exact failure this project exists to prevent.
        problems.append(
            Problem("no_citations", "the draft cites no evidence id")
        )

    for match in URL_RE.finditer(body):
        problems.append(
            Problem(
                "raw_url",
                f"wrote a URL instead of citing an id: {match.group(0)[:80]}",
            )
        )

    if not body.lstrip().startswith("# "):
        problems.append(Problem("missing_title", "draft must start with a level-1 title"))

    headings = [
        line.strip()[3:].strip()
        for line in body.splitlines()
        if line.strip().startswith("## ")
    ]
    lowered = [heading.lower() for heading in headings]
    for required in ("summary", "limitations"):
        if required not in lowered:
            problems.append(
                Problem("missing_section", f"no '## {required.capitalize()}' section")
            )
    content_sections = [
        heading
        for heading, low in zip(headings, lowered)
        if low not in {"summary", "limitations", "references"}
    ]
    if len(content_sections) < 2:
        problems.append(
            Problem(
                "missing_section",
                f"need at least 2 content sections, found {len(content_sections)}",
            )
        )

    for section, text in _iter_blocks(body):
        if section.lower().startswith("limitation"):
            continue  # limitations are meta-commentary, not claims
        if len(text) < 40:
            continue
        if not ID_RE.search(text):
            problems.append(
                Problem(
                    "uncited_paragraph",
                    f"no citation in: \"{text[:70]}...\"",
                )
            )

    return problems


def renumber(
    body: str, store: EvidenceStore
) -> tuple[str, list[tuple[str, int]], dict[str, int]]:
    """Turn [ev_x] into [1], numbering *sources* rather than individual quotes.

    Four passages from one page are one reference, not four. Per-quote detail
    lives in the appendix, where it is actually useful.
    """
    body = normalize_citations(body)
    url_number: dict[str, int] = {}
    id_number: dict[str, int] = {}
    for evidence_id in extract_ids(body):
        item = store.get(evidence_id)
        if item is None:
            id_number[evidence_id] = 0
            continue
        if item.url not in url_number:
            url_number[item.url] = len(url_number) + 1
        id_number[evidence_id] = url_number[item.url]

    def replace(match: re.Match[str]) -> str:
        ids = ID_RE.findall(match.group(1))
        if not ids:
            return match.group(0)
        numbers: list[int] = []
        for evidence_id in ids:
            number = id_number.get(evidence_id, 0)
            if number and number not in numbers:
                numbers.append(number)
        if not numbers:
            return match.group(0)
        return "[" + ", ".join(str(number) for number in numbers) + "]"

    return BRACKET_RE.sub(replace, body), list(url_number.items()), id_number


def _collapse_brackets(text: str) -> str:
    """[1][1] -> [1]; [1][1][2] -> [1, 2]. Source-level citations merge."""
    pattern = re.compile(r"(?:\[\s*\d[\d,\s]*\]){2,}")

    def merge(match: re.Match[str]) -> str:
        numbers: list[str] = []
        for group in re.findall(r"\[\s*([\d,\s]+)\]", match.group(0)):
            for number in group.split(","):
                number = number.strip()
                if number and number not in numbers:
                    numbers.append(number)
        return "[" + ", ".join(numbers) + "]"

    return pattern.sub(merge, text)


def render_references(url_order: list[tuple[str, int]], store: EvidenceStore) -> str:
    first_by_url: dict[str, Evidence] = {}
    for item in store.items:
        first_by_url.setdefault(item.url, item)

    lines = ["## References", ""]
    for url, number in sorted(url_order, key=lambda pair: pair[1]):
        item = first_by_url.get(url)
        title = (item.title if item and item.title else "") or domain(url)
        lines.append(f"{number}. {title} — {url}")
    return "\n".join(lines)


def render_appendix(
    cited_ids: list[str], store: EvidenceStore, id_number: dict[str, int]
) -> str:
    """The audit trail: one row per cited quote, with its offset in the page."""
    rows = ["## Evidence appendix", "", "| ref | claim | quote | span |", "| --- | --- | --- | --- |"]
    ordered = sorted(
        (store.get(evidence_id) for evidence_id in cited_ids),
        key=lambda item: (id_number.get(item.id, 0), item.id) if item else (99, ""),
    )
    for item in ordered:
        if item is None:
            continue
        span = (
            f"{item.span_start}-{item.span_end}"
            if item.span_start is not None
            else "-"
        )
        claim = " ".join(item.claim.split()).replace("|", "/")[:110]
        quote = " ".join(item.quote.split()).replace("|", "/")[:150]
        rows.append(f"| [{id_number.get(item.id, '?')}] | {claim} | \"{quote}\" | {span} |")
    return "\n".join(rows)


def _strip_fences(text: str) -> str:
    return strip_fences(text)


class ReportWriter:
    def __init__(
        self,
        client: LLMClient,
        *,
        max_tokens: int = 1800,
        temperature: float = 0.3,
        repair_attempts: int = 1,
        reasoning_effort: str | None = "low",
    ) -> None:
        self.client = client
        self.max_tokens = max_tokens
        self.temperature = temperature
        self.repair_attempts = repair_attempts
        # Writing from a fixed evidence list benefits from less hidden
        # deliberation, and a reasoning model that spends 1,800-3,600 tokens
        # thinking can return empty `content`. Low effort made this stochastic
        # failure disappear in the reproducibility check; keep it configurable
        # so a caller can turn it off for a model that ignores the hint.
        self.reasoning_effort = reasoning_effort

    async def _complete(
        self,
        messages: list[Message],
        *,
        temperature: float,
        max_tokens: int,
    ) -> tuple[LLMResponse, Usage]:
        """Ask for markdown, retrying once when the completion is unusable.

        Reasoning models sometimes spend the whole output budget on hidden
        reasoning and return empty `content` with `finish_reason='stop'`. That is
        not a draft with fixable citation errors, so the repair prompt cannot
        help. Retry from scratch with a larger budget instead. The same applies
        when the provider stops the response at the token limit.
        """
        usage = Usage()
        budget = max_tokens
        prompt = list(messages)
        response: LLMResponse | None = None

        for attempt in range(2):
            response = await self.client.chat(
                prompt,
                temperature=temperature,
                max_tokens=budget,
                reasoning_effort=self.reasoning_effort,
            )
            usage += response.usage
            content = (response.message.content or "").strip()
            if content and not response.truncated:
                break
            if attempt == 0:
                budget = max(budget * 2, 3000)
                prompt = [*prompt, Message.user(EMPTY_RETRY_PROMPT)]

        assert response is not None
        return response, usage

    async def write(
        self,
        *,
        question: str,
        store: EvidenceStore,
        plan: Plan | None = None,
        gaps: Sequence[str] = (),
    ) -> Report:
        items = store.citable()
        if not items:
            raise WriterError("no citable evidence: every record failed verification")

        allowed = {item.id for item in items}
        uncovered: list[str] = []
        if plan is not None:
            covered = {
                sub_question
                for item in items
                for sub_question in item.sub_questions
            }
            uncovered = [
                sub.question
                for sub in plan.sub_questions
                if sub.question not in covered
            ]
            outline_lines = [f"- {sq.question}" for sq in plan.sub_questions]
            restated = plan.restated
        else:
            # Stages are decoupled: a saved store has no plan attached, so derive
            # the outline from the sub-questions that actually produced evidence.
            seen: list[str] = []
            for item in items:
                for sub_question in item.sub_questions:
                    if sub_question and sub_question not in seen:
                        seen.append(sub_question)
            outline_lines = [f"- {sub_question}" for sub_question in seen[:5]]
            restated = question
        outline = "\n".join(outline_lines) or "- (no outline recorded)"
        gap_lines = [f"- {gap}" for gap in gaps]
        gap_lines.extend(
            f"- no evidence was extracted for: {sub_question}"
            for sub_question in uncovered
        )
        gap_text = "\n".join(gap_lines) or "- none recorded"
        uncovered_text = "\n".join(f"- {item}" for item in uncovered) or "- none"
        user = (
            f"QUESTION: {question}\n\n"
            f"RESTATED: {restated}\n\n"
            f"SUB-QUESTIONS TO COVER:\n{outline}\n\n"
            f"UNCOVERED SUB-QUESTIONS (do not answer from general knowledge):\n"
            f"{uncovered_text}\n\n"
            f"GAPS FOUND DURING RESEARCH:\n{gap_text}\n\n"
            f"EVIDENCE (the only legal ids):\n{build_brief(items)}"
        )
        messages: list[Message] = [
            Message.system(WRITER_PROMPT),
            Message.user(user),
        ]

        usage = Usage()
        response, spent = await self._complete(
            messages,
            temperature=self.temperature,
            max_tokens=self.max_tokens,
        )
        usage += spent
        body = normalize_citations(_strip_fences(response.message.content))
        messages.append(response.message)

        problems = check_draft(body, allowed)
        if not body.strip():
            problems.append(
                Problem(
                    "empty_draft",
                    "the writer returned no markdown after a retry with a larger budget",
                )
            )
        initial_errors = [p for p in problems if p.severity == "error"]
        repaired = False

        # An empty body has nothing to repair. Sending the same request again
        # just burns another truncated reasoning completion.
        if body.strip():
            for _ in range(self.repair_attempts):
                errors = [p for p in problems if p.severity == "error"]
                if not errors:
                    break
                listing = "\n".join(f"- {p.code}: {p.detail}" for p in errors)
                messages.append(
                    Message.user(REPAIR_PROMPT.format(problems=listing))
                )
                response, spent = await self._complete(
                    messages,
                    temperature=0.0,
                    max_tokens=max(self.max_tokens * 2, 3000),
                )
                usage += spent
                body = normalize_citations(
                    _strip_fences(response.message.content)
                )
                messages.append(response.message)
                problems = check_draft(body, allowed)
                if not body.strip():
                    problems.append(
                        Problem(
                            "empty_draft",
                            "the writer returned no markdown after a repair",
                        )
                    )
                repaired = True

        cited = extract_ids(body)
        unused = [item.id for item in items if item.id not in cited]
        warnings = [
            Problem(
                "unused_evidence",
                f"{len(unused)} verified record(s) never cited",
                severity="warning",
            )
        ] if unused else []

        numbered, url_order, id_number = renumber(body, store)
        numbered = _collapse_brackets(numbered)
        references = render_references(url_order, store)
        appendix = render_appendix(cited, store, id_number)
        footer = (
            f"\n\n---\n*{len(cited)} passages from {len(url_order)} sources. "
            "Every quote was located in the fetched page at the character offset "
            "shown in the appendix before this was written.*"
        )
        markdown = f"{numbered.strip()}\n\n{references}\n\n{appendix}{footer}"

        return Report(
            markdown=markdown,
            body=body,
            errors=[p for p in problems if p.severity == "error"],
            initial_errors=initial_errors,
            warnings=warnings + [p for p in problems if p.severity == "warning"],
            cited_ids=cited,
            unused_ids=unused,
            usage=usage,
            repaired=repaired,
            sections=len([line for line in body.splitlines() if line.startswith("## ")]),
            word_count=len(numbered.split()),
        )
